"""Playwright demonstration script that visits /test with plain headless Chromium.

This script launches an unconfigured, default headless Chromium browser instance
(without stealth plugins or anti-detection flags) and visits the /test endpoint.
The server and client-side checks will flag it as an automated headless bot.

Usage:
    python examples/run_headless_check.py
    python examples/run_headless_check.py --url http://127.0.0.1:8000/test
"""

import argparse
import subprocess
import sys
import time
from urllib.request import urlopen

from playwright.sync_api import sync_playwright

# ANSI terminal color codes
RED = "\033[91m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
CYAN = "\033[96m"
BOLD = "\033[1m"
RESET = "\033[0m"


def is_server_ready(base_url: str) -> bool:
    """Check if the fingerprint-check server is responding."""
    try:
        with urlopen(f"{base_url}/health", timeout=1) as resp:
            return resp.status == 200
    except Exception:
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description="Audit headless Chromium fingerprint against /test")
    parser.add_argument("--url", default="http://127.0.0.1:8000/test", help="Target URL (default: http://127.0.0.1:8000/test)")
    args = parser.parse_args()

    base_url = args.url.split("/test")[0]
    server_process = None

    # Automatically launch uvicorn if not already running
    if not is_server_ready(base_url):
        print(f"{CYAN}Starting local fingerprint-check server on {base_url}...{RESET}")
        server_process = subprocess.Popen(
            [sys.executable, "-m", "uvicorn", "fingerprint_check.main:app", "--host", "127.0.0.1", "--port", "8000"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        # Wait up to 10 seconds for server startup
        for _ in range(20):
            if is_server_ready(base_url):
                break
            time.sleep(0.5)

        if not is_server_ready(base_url):
            print(f"{RED}Error: Failed to start or connect to server at {base_url}{RESET}")
            if server_process:
                server_process.terminate()
            return 1

    try:
        print(f"\n{BOLD}{CYAN}=== Launching Plain Headless Chromium with Playwright ==={RESET}")
        print("Configuration: headless=True (no stealth, default args)\n")

        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            page = browser.new_page()

            print(f"Navigating to {args.url}...")
            page.goto(args.url)

            # Wait for client-side JavaScript execution and report rendering
            page.wait_for_selector("#report-summary", state="visible", timeout=15000)

            # Retrieve the complete report generated by server and browser
            report = page.evaluate("() => window.__report__")

            browser.close()

        if not report:
            print(f"{RED}Error: Failed to retrieve report from page.{RESET}")
            return 1

        summary = report.get("summary", {})
        checks = report.get("checks", [])

        print(f"\n{BOLD}=== Audit Results Summary ==={RESET}")
        print(f"Total Checks : {summary.get('total')}")
        print(f"{GREEN}Passed       : {summary.get('passed')}{RESET}")
        print(f"{YELLOW}Warned       : {summary.get('warned')}{RESET}")
        print(f"{RED}Failed       : {summary.get('failed')}{RESET}\n")

        print(f"{BOLD}=== Individual Check Details ==={RESET}\n")
        for check in checks:
            status = check.get("status", "pass").upper()
            name = check.get("name")
            explanation = check.get("explanation")
            fix = check.get("fix") or check.get("fix_suggestion")

            if status == "FAIL":
                badge = f"{RED}[FAIL]{RESET}"
            elif status == "WARN":
                badge = f"{YELLOW}[WARN]{RESET}"
            else:
                badge = f"{GREEN}[PASS]{RESET}"

            print(f"{badge} {BOLD}{name}{RESET}")
            if status in ("FAIL", "WARN"):
                print(f"       {BOLD}Why it matters:{RESET} {explanation}")
                print(f"       {CYAN}Fix suggestion:{RESET} {fix}")
            print()

        if summary.get("failed", 0) > 0:
            print(f"{BOLD}{RED}[FLAGGED AS BOT]{RESET} Plain headless Chromium was successfully detected and flagged.\n")
        else:
            print(f"{BOLD}{GREEN}[CLEAN]{RESET} All checks passed.\n")

        return 0

    finally:
        if server_process:
            server_process.terminate()
            server_process.wait()


if __name__ == "__main__":
    sys.exit(main())
